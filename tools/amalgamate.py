#!/usr/bin/env python3
"""Bundle the modular firmware into one main.c for the wokwi.com web editor.

The web editor's STM32 HAL template compiles a single main.c, so this script
inlines the project headers and sources in dependency order. The modular
files in firmware/ remain the source of truth; re-run after editing them:

    python3 tools/amalgamate.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INC = ROOT / "firmware/Core/Inc"
SRC = ROOT / "firmware/Core/Src"
OUT = ROOT / "wokwi/main.c"

ORDER = [INC / "ddc.h", INC / "keypad.h", INC / "switcher.h", INC / "sw_i2c.h", INC / "config.h",
         SRC / "ddc.c", SRC / "keypad.c", SRC / "switcher.c", SRC / "sw_i2c.c", SRC / "main.c"]

LOCAL_INCLUDE = re.compile(r'^\s*#include\s+"(ddc|keypad|switcher|sw_i2c|config)\.h"\s*$')


def main() -> None:
    parts = [
        "/*\n"
        " * AUTO-GENERATED by tools/amalgamate.py - do not edit here.\n"
        " * Source of truth: firmware/Core/Inc and firmware/Core/Src.\n"
        " * Single-file build for the wokwi.com STM32 HAL editor.\n"
        " */\n"
    ]
    for path in ORDER:
        lines = path.read_text().splitlines()
        body = [l for l in lines if not LOCAL_INCLUDE.match(l)]
        rel = path.relative_to(ROOT)
        parts.append(f"\n/* {'=' * 66}\n *  {rel}\n * {'=' * 66} */\n")
        parts.append("\n".join(body) + "\n")
    OUT.write_text("".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)} ({sum(p.count(chr(10)) for p in parts)} lines)")


if __name__ == "__main__":
    main()
